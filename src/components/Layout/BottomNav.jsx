import React from 'react';
import { Link, useLocation } from 'react-router-dom';
import { useAuth } from '../../context/AuthContext';
import './BottomNav.css';

export default function BottomNav() {
  const { checkedInStaff } = useAuth();
  const location = useLocation();

  if (!checkedInStaff) return null;

  const menuItems = [
    { path: '/', label: 'Shift', icon: 'grid', roles: ['Admin', 'Manager', 'Staff'] },
    { path: '/history', label: 'History', icon: 'clock', roles: ['Admin', 'Manager'] },
    { path: '/staff', label: 'Users', icon: 'users', roles: ['Admin', 'Manager'] },
    { path: '/config', label: 'Config', icon: 'settings', roles: ['Admin', 'Manager'] },
  ];

  const isActive = (path) => location.pathname === path;
  const canViewItem = (roles) => roles.includes(checkedInStaff.role);

  return (
    <nav className="bottom-nav">
      {menuItems.map(item => 
        canViewItem(item.roles) && (
          <Link 
            key={item.path} 
            to={item.path} 
            className={`bottom-nav-item ${isActive(item.path) ? 'active' : ''}`}
          >
            <NavIcon name={item.icon} />
            <span>{item.label}</span>
          </Link>
        )
      )}
    </nav>
  );
}

